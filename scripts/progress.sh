#!/bin/sh
# Почасовой прогресс — п. 6.6 регламента HackAlem: отсутствие подтверждённого
# результата за любой отчётный час = основание для дисквалификации КОМАНДЫ.
# Использование: bun run progress "что сделал"
msg="$*"
[ -z "$msg" ] && msg="wip"
git add -A
if git commit -m "progress($(date +%H:%M)): $msg"; then
  git push 2>/dev/null || echo "⚠️  push не прошёл — проверь remote (репо должно быть на edu.astanahub.com, п. 6.8)"
else
  echo "⚠️  Коммитить нечего. За этот час нужен подтверждённый результат — хотя бы коммит схемы, README или теста."
fi
